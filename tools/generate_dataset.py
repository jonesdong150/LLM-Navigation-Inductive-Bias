#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Dataset Generation Pipeline

Automatically generates all navigation planning dataset variants:
- R1: Simple navigation scenes (10 scenes) — structural variants at 100%/50%/25% retention
- R2: Complex navigation scenes (10 scenes, G1-G5) — dimension-ablation + structural variants
- Conflict: Conflict test scenes (10 scenes) — conflict + semantic conflict variants

Scene worlds are generated by tools/build_scene.py using the knowledge base.
Text serialization is handled by tools/scene_serializer.py.

All generation is rule-based, deterministic, and requires no human or LLM annotation.
"""

import os
import sys
import json
import csv
import random
import argparse
from pathlib import Path
from typing import Dict, List

_PROJECT_ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(_PROJECT_ROOT))

from tools.build_scene import generate_world, generate_simple_world
from tools.scene_serializer import (
    generate_all_variants,
    generate_dimension_variants,
    generate_conflict_variants,
    generate_semantic_variation,
    generate_semantic_conflict,
    parse_world,
)


def ensure_dir(path: str):
    os.makedirs(path, exist_ok=True)


def generate_queries_for_scene(scene: Dict, num_queries: int = 50) -> List[Dict]:
    """Generate navigation queries for a scene.

    Query types (evenly distributed):
    - ObjectLocation: Where is object X?
    - GeometryYN: Is room A north/south of room B?
    - TopologyYN: Is there a direct connection between A and B?
    - ReachabilityYN: Can I reach B from A?
    - PathGen: Find shortest path from A to B

    All ground truths are computed by symbolic solvers (BFS, direct lookup, etc.).
    """
    random.seed(42)

    world = scene.get("world", scene)
    rooms = world.get("rooms", [])
    edges = world.get("edges", [])
    objects = world.get("objects", {})

    if not rooms:
        return []

    queries = []
    room_ids = [r.get("room_id", f"R{i+1}") for i, r in enumerate(rooms)]

    # Build adjacency list
    adj = {i: [] for i in range(len(rooms))}
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)

    # ObjectLocation queries (10)
    for i in range(min(10, num_queries)):
        room_idx = i % len(rooms)
        room_objects = objects.get(str(room_idx), objects.get(room_idx, []))
        if room_objects:
            obj = room_objects[0]
            if isinstance(obj, dict):
                obj_name = obj.get("canonical", obj.get("name", "object"))
            else:
                _, obj_name = obj
            queries.append({
                "question_id": f"q{i + 1:02d}",
                "task_type": "ObjectLocation",
                "question_text": f"Where is the {obj_name} currently located?",
                "answer_format": "ROOM_ID",
                "ground_truth": room_ids[room_idx]
            })

    # GeometryYN queries (10)
    for i in range(10, min(20, num_queries)):
        idx1, idx2 = random.sample(range(len(rooms)), 2)
        if idx1 != idx2:
            r1, r2 = rooms[idx1], rooms[idx2]
            y1, y2 = r1.get("y", 0), r2.get("y", 0)
            if y1 > y2:
                direction, truth = "North", "YES"
            elif y1 < y2:
                direction, truth = "South", "YES"
            else:
                direction, truth = "at the same latitude as", "YES"
            r1_type = r1.get("canonical", r1.get("type", "Room"))
            r2_type = r2.get("canonical", r2.get("type", "Room"))
            queries.append({
                "question_id": f"q{i + 1:02d}",
                "task_type": "GeometryYN",
                "question_text": (
                    f"Is the {r1_type} ({room_ids[idx1]}) "
                    f"located {direction} the {r2_type} ({room_ids[idx2]})?"
                ),
                "answer_format": "YES_NO",
                "ground_truth": truth
            })

    # TopologyYN queries (10)
    for i in range(20, min(30, num_queries)):
        idx1, idx2 = random.sample(range(len(rooms)), 2)
        has_edge = idx2 in adj[idx1]
        queries.append({
            "question_id": f"q{i + 1:02d}",
            "task_type": "TopologyYN",
            "question_text": f"Is there a direct connection between {room_ids[idx1]} and {room_ids[idx2]}?",
            "answer_format": "YES_NO",
            "ground_truth": "YES" if has_edge else "NO"
        })

    # ReachabilityYN queries (10)
    for i in range(30, min(40, num_queries)):
        idx1, idx2 = random.sample(range(len(rooms)), 2)
        visited = {idx1}
        queue = [idx1]
        while queue:
            curr = queue.pop(0)
            for neighbor in adj[curr]:
                if neighbor not in visited:
                    visited.add(neighbor)
                    queue.append(neighbor)
        reachable = idx2 in visited
        queries.append({
            "question_id": f"q{i + 1:02d}",
            "task_type": "ReachabilityYN",
            "question_text": f"Can you reach {room_ids[idx2]} from {room_ids[idx1]}?",
            "answer_format": "YES_NO",
            "ground_truth": "YES" if reachable else "NO"
        })

    # PathGen queries (10)
    for i in range(40, min(50, num_queries)):
        idx1, idx2 = random.sample(range(len(rooms)), 2)
        # BFS shortest path with lexicographic tie-breaking
        parents = {idx1: [idx1]}
        queue = [idx1]
        found = False
        while queue and not found:
            curr = queue.pop(0)
            for neighbor in sorted(adj[curr]):  # sorted for lexicographic order
                if neighbor not in parents:
                    parents[neighbor] = parents[curr] + [neighbor]
                    queue.append(neighbor)
                    if neighbor == idx2:
                        found = True
                        break
        if idx2 in parents:
            path = "->".join([room_ids[idx] for idx in parents[idx2]])
        else:
            path = "UNREACHABLE"
        queries.append({
            "question_id": f"q{i + 1:02d}",
            "task_type": "PathGen",
            "question_text": f"Provide the shortest path from {room_ids[idx1]} to {room_ids[idx2]}.",
            "answer_format": "PATH",
            "ground_truth": path
        })

    return queries[:num_queries]


def write_queries_csv(queries: List[Dict], output_path: str):
    ensure_dir(os.path.dirname(output_path))
    fieldnames = ["question_id", "task_type", "question_text", "answer_format", "ground_truth"]
    with open(output_path, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for query in queries:
            writer.writerow(query)


def main():
    parser = argparse.ArgumentParser(
        description="Generate navigation planning dataset (rule-based, deterministic)"
    )
    parser.add_argument("--output_dir", default="./data_set", help="Output directory")
    parser.add_argument("--r1_scenes", type=int, default=10, help="Number of R1 scenes")
    parser.add_argument("--r2_scenes", type=int, default=10, help="Number of R2 scenes")
    parser.add_argument("--conflict_scenes", type=int, default=10, help="Number of conflict scenes")
    parser.add_argument("--queries_per_scene", type=int, default=50, help="Queries per scene")
    parser.add_argument("--seed", type=int, default=42, help="Random seed for reproducibility")
    parser.add_argument("--dry_run", action="store_true", help="Print summary only, do not generate")

    args = parser.parse_args()
    output_dir = Path(args.output_dir)

    if args.dry_run:
        total_scenes = args.r1_scenes + args.r2_scenes + args.conflict_scenes
        total_queries = total_scenes * args.queries_per_scene
        print("=== Dry Run ===")
        print(f"R1 scenes: {args.r1_scenes} (Flat/Hier/Clustered at 100%/50%/25% retention)")
        print(f"R2 scenes: {args.r2_scenes} (dimension-ablation + structural variants)")
        print(f"Conflict scenes: {args.conflict_scenes} (base + conflict + semantic conflict)")
        print(f"Total scenes: {total_scenes}")
        print(f"Queries per scene: {args.queries_per_scene}")
        print(f"Total queries: {total_queries}")
        return

    print("=" * 60)
    print("Navigation Planning Dataset Generator")
    print("=" * 60)
    print(f"Seed: {args.seed} (deterministic, rule-based, no human/LLM annotation)")

    total_queries = 0

    # ============================================================
    # R1: Simple navigation scenes — structural variants
    # ============================================================
    print("\n[R1] Generating simple navigation scenes...")
    r1_scene_dir = output_dir / "R1" / "scene"
    r1_query_dir = output_dir / "R1" / "queries"
    ensure_dir(str(r1_scene_dir))
    ensure_dir(str(r1_query_dir))

    for i in range(1, args.r1_scenes + 1):
        world_dict = generate_simple_world(i, seed=args.seed * 1000 + i)

        # R1 uses structural variants (Flat/Hier/Clustered at 100%/50%/25%)
        variants = generate_all_variants(world_dict)

        # Add semantic variation variants
        sem_variants = generate_semantic_variation(world_dict, seed=args.seed * 1000 + i + 500)
        for k, v in sem_variants.items():
            variants[f"semvar_{k}"] = v

        scene_data = {
            "scene_id": f"scene_simple_{i:02d}",
            "description": f"Simple navigation scene {i:02d} ({len(world_dict['rooms'])} rooms)",
            "world": world_dict,
            "variants": variants,
        }

        scene_path = r1_scene_dir / f"scene_{i:02d}.json"
        with open(scene_path, "w", encoding="utf-8") as f:
            json.dump(scene_data, f, ensure_ascii=False, indent=2)

        queries = generate_queries_for_scene(scene_data, args.queries_per_scene)
        query_path = r1_query_dir / f"scene_{i:02d}_questions.csv"
        write_queries_csv(queries, str(query_path))
        total_queries += len(queries)
        print(f"  [R1] scene_{i:02d}: {len(variants)} variants, {len(queries)} queries")

    # ============================================================
    # R2: Complex navigation scenes — dimension-ablation + structural
    # ============================================================
    print("\n[R2] Generating complex navigation scenes...")
    r2_scene_dir = output_dir / "R2" / "scene"
    r2_query_dir = output_dir / "R2" / "queries"
    ensure_dir(str(r2_scene_dir))
    ensure_dir(str(r2_query_dir))

    for i in range(1, args.r2_scenes + 1):
        world_dict = generate_world(i, seed=args.seed * 2000 + i)

        # R2 uses dimension-ablation + structural variants
        dim_variants = generate_dimension_variants(world_dict)
        struct_variants = generate_all_variants(world_dict)
        variants = {**dim_variants, **struct_variants}

        # Add semantic variation variants
        sem_variants = generate_semantic_variation(world_dict, seed=args.seed * 2000 + i + 500)
        for k, v in sem_variants.items():
            variants[f"semvar_{k}"] = v

        scene_data = {
            "scene_id": f"scene_complex_{i:02d}",
            "description": f"Complex scene {i:02d}: {world_dict['gradient']} - {world_dict['gradient_label']} ({len(world_dict['rooms'])} rooms)",
            "world": world_dict,
            "variants": variants,
        }

        scene_path = r2_scene_dir / f"scene_complex_{i:02d}.json"
        with open(scene_path, "w", encoding="utf-8") as f:
            json.dump(scene_data, f, ensure_ascii=False, indent=2)

        queries = generate_queries_for_scene(scene_data, args.queries_per_scene)
        query_path = r2_query_dir / f"scene_complex_{i:02d}_questions.csv"
        write_queries_csv(queries, str(query_path))
        total_queries += len(queries)
        print(f"  [R2] scene_complex_{i:02d}: {len(variants)} variants, {len(queries)} queries")

    # ============================================================
    # Conflict: Conflict test scenes
    # ============================================================
    print("\n[Conflict] Generating conflict test scenes...")
    conflict_scene_dir = output_dir / "conflict" / "scene"
    conflict_query_dir = output_dir / "conflict" / "queries"
    ensure_dir(str(conflict_scene_dir))
    ensure_dir(str(conflict_query_dir))

    for i in range(1, args.conflict_scenes + 1):
        world_dict = generate_world(i, seed=args.seed * 3000 + i)

        # Conflict scenes: base + conflict + semantic conflict
        variants = generate_conflict_variants(world_dict, seed=args.seed * 3000 + i)

        scene_data = {
            "scene_id": f"scene_conflict_{i:02d}",
            "description": f"Conflict scene {i:02d}: {world_dict['gradient']} - {world_dict['gradient_label']} ({len(world_dict['rooms'])} rooms)",
            "world": world_dict,
            "variants": variants,
        }

        scene_path = conflict_scene_dir / f"scene_conflict_{i:02d}.json"
        with open(scene_path, "w", encoding="utf-8") as f:
            json.dump(scene_data, f, ensure_ascii=False, indent=2)

        queries = generate_queries_for_scene(scene_data, args.queries_per_scene)
        query_path = conflict_query_dir / f"scene_conflict_{i:02d}_questions.csv"
        write_queries_csv(queries, str(query_path))
        total_queries += len(queries)
        print(f"  [Conflict] scene_conflict_{i:02d}: {len(variants)} variants, {len(queries)} queries")

    # ============================================================
    # Summary
    # ============================================================
    total_scenes = args.r1_scenes + args.r2_scenes + args.conflict_scenes
    print("\n" + "=" * 60)
    print("Generation Complete")
    print("=" * 60)
    print(f"Total scenes:             {total_scenes}")
    print(f"Total queries:            {total_queries}")
    print(f"R1: Flat/Hier/Clustered at 100%/50%/25% retention + semantic variation")
    print(f"R2: Dimension-ablation + structural + semantic variation variants")
    print(f"Conflict: Base + conflict + semantic conflict variants")
    print(f"Output directory:         {output_dir.absolute()}")
    print("=" * 60)
    print("All data generated deterministically with rule-based serialization.")
    print("No human annotation or LLM-based annotation was used.")


if __name__ == "__main__":
    main()
